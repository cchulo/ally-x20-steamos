# components/update.sh — SteamOS A/B update survival (plan §4).
#
# Owns:
#   * the boot service  /etc/systemd/system/ally-x20-steamos.service
#     (+ multi-user.target.wants link) — re-applies what an update dropped;
#   * the user notifier /etc/systemd/user/ally-x20-steamos-notify.service
#     (+ default.target.wants link);
#   * the RAUC handlers  /var/lib/ally-x20-steamos/libexec/rauc-{pre,post}-install.hook
#     and their registration in /etc/rauc/system.conf (documented exception,
#     lib/rauc.sh);
#   * reconciling the booted slot's boot entry with the desired state that
#     other components declare through slots_desired_set (documented
#     exception, lib/slots.sh).
# The enable links are created through manifest_install_symlink, not
# `systemctl enable`, so uninstall removes exactly what we added.

# shellcheck source=lib/rauc.sh
. "$AX20_SRC/lib/rauc.sh"
# shellcheck source=lib/slots.sh
. "$AX20_SRC/lib/slots.sh"

# shellcheck disable=SC2034  # read by lib/component.sh
COMPONENT_DESCRIPTION="survive SteamOS updates: RAUC pre/post-install handlers, boot re-apply service, notifier"

UPDATE_UNIT="${AX20_NAME}.service"
UPDATE_NOTIFY_UNIT="${AX20_NAME}-notify.service"

update_files() {
    printf 'systemd/%s\t/etc/systemd/system/%s\t0644\n' "$UPDATE_UNIT" "$UPDATE_UNIT"
    printf 'systemd/%s\t/etc/systemd/user/%s\t0644\n' "$UPDATE_NOTIFY_UNIT" "$UPDATE_NOTIFY_UNIT"
    printf 'rauc/pre-install.hook\t%s\t0755\n' "$RAUC_PRE_HANDLER_REL"
    printf 'rauc/post-install.hook\t%s\t0755\n' "$RAUC_POST_HANDLER_REL"
}

update_apply() {
    local slot
    manifest_install_symlink "../$UPDATE_UNIT" \
        "/etc/systemd/system/multi-user.target.wants/$UPDATE_UNIT" update
    manifest_install_symlink "../$UPDATE_NOTIFY_UNIT" \
        "/etc/systemd/user/default.target.wants/$UPDATE_NOTIFY_UNIT" update
    rauc_register "$RAUC_PRE_HANDLER_REL" "$RAUC_POST_HANDLER_REL"
    if slot=$(slots_active 2>/dev/null); then
        slots_entry_reconcile "$slot"
    else
        log_debug "update: active slot unknown; boot entry left alone"
    fi
    if [ -z "$AX20_ROOT" ] && [ "$AX20_DRY_RUN" != 1 ] && ax20_have systemctl; then
        systemctl daemon-reload >/dev/null 2>&1 || true
    fi
    return 0
}

# Never superseded: this is our own re-apply machinery, there is no stock
# SteamOS feature that could replace it. (Retire it together with the last
# other component.)
update_probe() {
    return "$PROBE_NO"
}

# Default status, plus the two things the manifest cannot see: our RAUC
# block (a SteamOS update gives the new slot a stock system.conf) and the
# boot entry (regenerated by steamos-finalize-install on update).
update_status() {
    local st slot
    st=$(component_default_status update)
    if [ "$st" = active ]; then
        rauc_registered "$RAUC_PRE_HANDLER_REL" "$RAUC_POST_HANDLER_REL" || st=stock
        if slot=$(slots_active 2>/dev/null) && ! slots_entry_in_sync "$slot"; then
            st=stock
        fi
    fi
    printf '%s\n' "$st"
}

update_remove() {
    local slot
    rauc_unregister
    if slot=$(slots_active 2>/dev/null); then
        slots_entry_restore "$slot"
    fi
    # The units and their enable links are manifest entries; uninstall
    # removes them and runs daemon-reload afterwards.
    return 0
}
