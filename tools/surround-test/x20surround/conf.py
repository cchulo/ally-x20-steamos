"""Generate a standalone PipeWire filter-chain config for one candidate.

The graph is PipeWire 1.6.8's sink-virtual-surround-7.1-hesuvi.conf (copy
nodes, 14 + 2 convolvers reading one 14-channel WAV, two mixers) with three
additions:
  - the level trim and the LFE gain as mixer gains,
  - a hard ceiling (builtin `clamp`) on each output,
  - the output pinned to one hardware sink (target.object +
    node.dont-fallback), so a candidate never falls back to another sink
    (docs/audio-dsp-history.md, "the silent x20-speakers bug"), plus
    node.linger: without it WirePlumber 0.5 destroys a filter whose target
    is missing, and a stream aimed at the vanished sink then lands on the
    default sink (measured with pw-harness.sh pin).
The file is a complete config for `pipewire -c <file>`: each candidate runs
as its own process next to the user's PipeWire and disappears when that
process is stopped. Nothing is written to ~/.config/pipewire.
"""

from .layout import HESUVI, HESUVI_INDEX, INPUTS

# Ceiling of the output samples: -1 dBFS.
CEILING = 0.891
LFE_GAIN = 0.5
# Never the automatic default: the hardware sinks have 712 and 1000.
PRIORITY = 1

_HEADER = """\
# Generated by tools/surround-test (ally-x20-steamos); do not edit.
# candidate: {label}
# hrir: {wav}
# target: {target}
context.properties = {{
    log.level = 2
}}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt
        args = {{ }}
        flags = [ ifexists nofail ]
    }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-filter-chain
        args = {{
            node.description = "{description}"
            media.name       = "{description}"
            filter.graph = {{
                nodes = [
"""

_FOOTER = """\
                ]
                inputs  = [ {inputs} ]
                outputs = [ "limL:Out" "limR:Out" ]
            }}
            capture.props = {{
                node.name        = "{node}"
                node.description = "{description}"
                media.class      = Audio/Sink
                audio.channels   = 8
                audio.position   = [ {positions} ]
                priority.session = {priority}
                priority.driver  = {priority}
            }}
            playback.props = {{
                node.name          = "{node}.output"
                node.description   = "{description} output"
                node.passive       = true
                audio.channels     = 2
                audio.position     = [ FL FR ]
                target.object      = "{target}"
                node.dont-fallback = true
                node.linger        = true
            }}
        }}
    }}
]
"""


def _quote(text):
    if any(ch in text for ch in '"\\\n'):
        raise ValueError("unsupported character in %r" % text)
    return text


def convolvers():
    """[(node name, input channel, ear, WAV channel)] for the 16 convolvers:
    the 14 HeSuVi channels plus the LFE through the centre pair."""
    out = [("conv%s_%s" % (c, ear), c, ear, i) for i, (c, ear) in enumerate(HESUVI)]
    for ear in ("L", "R"):
        out.append(("convLFE_%s" % ear, "LFE", ear, HESUVI_INDEX[("FC", ear)]))
    return out


def render(label, node, description, wav, target, gain=1.0, lfe_gain=LFE_GAIN,
           ceiling=CEILING):
    """Return the config text.

    label: free text for the header comment; node: the sink's node.name;
    wav: absolute path of the 14-channel 48 kHz file; target: node.name of
    the hardware sink; gain: linear level trim.
    """
    if not wav.startswith("/"):
        raise ValueError("the HRIR path must be absolute: %r" % wav)
    for value in (label, node, description, wav, target):
        _quote(value)
    if not 0.0 < ceiling <= 1.0:
        raise ValueError("ceiling must be in (0, 1]")
    lines = []
    for c in INPUTS:
        lines.append("{ type = builtin label = copy name = copy%s }" % c)
    convs = convolvers()
    for name, _, _, channel in convs:
        lines.append(
            '{ type = builtin label = convolver name = %s config = { filename = "%s" channel = %d } }'
            % (name, wav, channel))
    slot = {"L": 0, "R": 0}
    links = []
    gains = {"L": [], "R": []}
    for name, c, ear, _ in convs:
        slot[ear] += 1
        links.append('{ output = "copy%s:Out" input = "%s:In" }' % (c, name))
        links.append('{ output = "%s:Out" input = "mix%s:In %d" }' % (name, ear, slot[ear]))
        value = gain * (lfe_gain if c == "LFE" else 1.0)
        gains[ear].append('"Gain %d" = %.6f' % (slot[ear], value))
    for ear in ("L", "R"):
        lines.append("{ type = builtin label = mixer name = mix%s control = { %s } }"
                     % (ear, " ".join(gains[ear])))
        lines.append('{ type = builtin label = clamp name = lim%s control = { "Min" = %.4f "Max" = %.4f } }'
                     % (ear, -ceiling, ceiling))
        links.append('{ output = "mix%s:Out" input = "lim%s:In" }' % (ear, ear))
    pad = " " * 20
    text = _HEADER.format(label=label, wav=wav, target=target, description=description)
    text += "".join(pad + line + "\n" for line in lines)
    text += " " * 16 + "]\n" + " " * 16 + "links = [\n"
    text += "".join(pad + line + "\n" for line in links)
    text += _FOOTER.format(
        inputs=" ".join('"copy%s:In"' % c for c in INPUTS),
        positions=" ".join(INPUTS), node=node, description=description,
        target=target, priority=PRIORITY)
    return text
